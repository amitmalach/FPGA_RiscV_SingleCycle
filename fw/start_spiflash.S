# =============================================================================
# start_spiflash.S -- startup code for programs that execute from SPI flash
# =============================================================================
# Tutorial step 24. This replaces start.S for flash-resident programs.
#
# The CPU's reset vector (Processor.v's RESET_PC, set from SOC.v's
# BOOT_ADDR) points at the very first byte of the flash code region, and the
# linker script (spiflash.ld) places this file's .text first
# in that region -- so _start below is literally the first instruction the
# processor executes after reset.
#
# It has three jobs before main() can safely run:
#   1. set up sp (stack) and gp (the memory-mapped IO base pointer)
#   2. zero the .bss section (uninitialised globals must read as 0 in C)
#   3. copy .data and fastcode from flash into RAM
#
# Steps 2 and 3 exist because .bss and .data live in RAM, which has no useful
# contents at power-on. Nothing does this automatically on bare metal -- if
# this file did not run, every initialised global would hold garbage.
#
# All the _sbss/_ebss/_sidata/_sdata/_edata symbols below are *generated by
# the linker script*, not defined here. See spiflash.ld.
# =============================================================================

.equ IO_BASE, 0x400000

.text
.global _start
.type _start, @function

_start:
# gp permanently holds the IO page base, so memory-mapped devices can be
# reached as IO_xxx(gp). norelax around it stops the assembler from
# "helpfully" repurposing gp for its own addressing optimisation.
.option push
.option norelax
     li  gp,IO_BASE
.option pop

# Stack grows DOWN from the top of the 6KB BRAM.
     li   sp,0x1800

# ---- 1. zero-init the .bss section (from _sbss up to _ebss) ----------------
# The bge guard handles the case of an empty .bss (nothing to do).
     la a0, _sbss
     la a1, _ebss
     bge a0, a1, end_init_bss
loop_init_bss:
     sw zero, 0(a0)
     addi a0, a0, 4
     blt a0, a1, loop_init_bss
end_init_bss:

# ---- 2. copy .data (+fastcode) from FLASH into RAM ------------------------
# a0 = _sidata, the LMA in flash where the initial bytes are stored
# a1 = _sdata,  the VMA in RAM where they belong at run time
# a2 = _edata,  one past the end of the RAM destination
#
# Each `lw a3, 0(a0)` here is a real SPI flash transaction (~1.9us), so this
# loop is by far the slowest part of boot -- expect a visible pause before
# any output appears, proportional to how much .data/fastcode there is.
# Both pointers are guaranteed 4-byte aligned by ALIGN(4) in the linker
# scripts, which is required for lw/sw.
     la a0, _sidata
     la a1, _sdata
     la a2, _edata
     bge a1, a2, end_init_data
loop_init_data:
     lw a3, 0(a0)
     sw a3, 0(a1)
     addi a0, a0, 4
     addi a1, a1, 4
     blt a1, a2, loop_init_data
end_init_data:

# ---- 3. hand over to the C program ----------------------------------------
     call main
     ebreak
