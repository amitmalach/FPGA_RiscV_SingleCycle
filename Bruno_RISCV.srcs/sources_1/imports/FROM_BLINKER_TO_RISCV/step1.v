`timescale 1ns/1ps
/*
 * Step 11 adaptation for your Genesys2 project.
 *
 * Main changes relative to your current Step 10 file:
 *   - Instruction memory is separated into a Memory module.
 *   - CPU logic is separated into a Processor module.
 *   - SOC is now mostly wiring: Clockworks + Memory + Processor + LEDs.
 *
 * Important project-specific choice kept from your implementation:
 *   - The program is loaded from program.hex using $readmemh().
 *   - We do NOT write the assembly program directly inside SOC.
 *
 * Top-level ports are kept compatible with your Genesys2 project:
 *   - sysclk_p/sysclk_n differential clock
 *   - RESET active-low CPU reset button
 *   - LEDS[7:0]
 *   - uart_rx_out / uart_tx_in, unused for now
 */


 // -----------------------------------------------------------------------------
 // SOC
 // -----------------------------------------------------------------------------
module SOC (        
    input  wire       sysclk_p,                // differential system clock +
    input  wire       sysclk_n,                // differential system clock -
    input  wire       RESET,                   // reset button
    output reg [7:0]  LEDS,                    // system LEDs
    input  wire       uart_rx_out,             // UART receive
    output wire       uart_tx_in               // UART transmit
);

    wire CLK_ibuf;                             // convert sysclk_p/sysclk_n into one single-ended FPGA clock signal, then route it globally.
    wire CLK;                                  // Main FPGA clock after global clock routing
    wire clk_enable;                           // clock enable generated by Clockworks
    wire resetn;                               // active-low reset generated by Clockworks
        
    wire [31:0] mem_addr;
    wire [31:0] mem_rdata;                     // The CPU still receives mem_rdata, but now mem_rdata can come from either RAM or I/O.
    wire        mem_rstrb;
    wire [31:0] mem_wdata;
    wire [3:0]  mem_wmask;
    
    wire [31:0] RAM_rdata;
    wire [29:0] mem_wordaddr = mem_addr[31:2];
    wire isIO  = mem_addr[22];
    wire isRAM = !isIO;
    wire mem_wstrb = |mem_wmask;
    
    localparam IO_LEDS_bit      = 0;  // write LEDs
    localparam IO_UART_DAT_bit  = 1;  // write UART data byte
    localparam IO_UART_CNTL_bit = 2;  // read UART status
    
    
    wire uart_valid = clk_enable && isIO & mem_wstrb & mem_wordaddr[IO_UART_DAT_bit];
    wire uart_ready;
        
    wire [31:0] IO_rdata =
        mem_wordaddr[IO_UART_CNTL_bit] ? {22'b0, !uart_ready, 9'b0} :
                                         32'b0;
                                         
        
    assign mem_rdata = isRAM ? RAM_rdata :
                IO_rdata ;                                     
                                         

        
    always @(posedge CLK) begin
        if (!resetn) begin
            LEDS <= 8'd0;
        end else if (clk_enable & isIO & mem_wstrb & mem_wordaddr[IO_LEDS_bit]) begin
            LEDS <= mem_wdata[7:0];
        end
    end
    
    // Instruction memory.
    Memory RAM (
        .clk        (CLK),
        .clk_enable (clk_enable),
        .mem_addr   (mem_addr),
        .mem_rdata  (RAM_rdata),
        .mem_rstrb  (isRAM && mem_rstrb),
        .mem_wdata  (mem_wdata),
        .mem_wmask({4{isRAM}}&mem_wmask)
    );
    
    // Processor.
    Processor CPU (
        .clk        (CLK),
        .clk_enable (clk_enable),
        .resetn     (resetn),
        .mem_addr   (mem_addr),
        .mem_rdata  (mem_rdata),
        .mem_rstrb  (mem_rstrb),
        .mem_wdata  (mem_wdata),
        .mem_wmask  (mem_wmask)
    );

    
    corescore_emitter_uart #(
        .clk_freq_hz(200000000)
    ) UART (
        .i_clk      (CLK),
        .i_rst      (!resetn),
        .i_data     (mem_wdata[7:0]),
        .i_valid    (uart_valid),
        .o_ready    (uart_ready),
        .o_uart_tx  (uart_tx_in)
    );
    
    `ifdef BENCH
    always @(posedge CLK) begin
        if (clk_enable && isIO && mem_wstrb) begin
            $display(
                "IO write: time=%0t mem_addr=%h mem_wordaddr=%h mem_wdata=%h mem_wmask=%b LED_write=%b UART_write=%b",
                $time,
                mem_addr,
                mem_wordaddr,
                mem_wdata,
                mem_wmask,
                mem_wordaddr[IO_LEDS_bit],
                mem_wordaddr[IO_UART_DAT_bit]
            );
        end
    
        if (uart_valid) begin
            $display("UART TX char: %c  hex=%02h", mem_wdata[7:0], mem_wdata[7:0]);
        end
    end
    `endif
    
    
    
   
    // -------------------------------------------------------------------------
    // Genesys2 clock handling
    // -------------------------------------------------------------------------
    // Genesys2 system clock is differential,
    // so convert sysclk_p/sysclk_n into one single-ended FPGA clock signal.
    IBUFDS sysclk_buffer (
        .I(sysclk_p),
        .IB(sysclk_n),
        .O(CLK_ibuf)
    );
    // Route the clock through the FPGA global clock network.
    // This gives low-skew clock distribution to all flip-flops that use CLK.
    BUFG sysclk_bufg (
        .I(CLK_ibuf),
        .O(CLK)
    );
    // Use a small slowdown for simulation and a larger slowdown for the board.
    `ifdef BENCH
    localparam integer SLOW_BITS = 0;
    `else
    localparam integer SLOW_BITS = 0;
    `endif
    // Clockworks generates:
    //   clk_enable = one-cycle enable pulse
    //   resetn     = active-low reset for the design
    Clockworks #(
        .SLOW(SLOW_BITS)
    ) clockworks (
        .CLK(CLK),
        .RESET(RESET),
        .clk_enable(clk_enable),
        .resetn(resetn)
    );
    

endmodule

